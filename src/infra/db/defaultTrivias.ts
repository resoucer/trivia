/** Deterministic position in 0..3 (FNV-1a hash), so the seed is stable across runs. */
function correctPosition(key: string): number {
  let hash = 0x811c9dc5;
  for (const char of key) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash % 4;
}
