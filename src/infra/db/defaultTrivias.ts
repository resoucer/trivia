import { z } from "zod";

export type { DefaultTrivia };
export { DEFAULT_TRIVIAS, defaultTriviaDraftInput, schema_DefaultTrivia };

/**
 * Default questionnaires shipped with the seed (pt-BR). Each question lists the correct option and
 * three wrong ones; `defaultTriviaDraftInput` places the correct one at a position derived from a hash
 * of the question (deterministic, but with no visible pattern) and
 * produces the same input the create endpoint accepts, so it is validated by `schema_TriviaDraft`.
 *
 * `playCount` values are FAKE, only so the demo ranking is not flat.
 * Avoid time-sensitive facts (records, "current" holders) when editing.
 */
const schema_DefaultQuestion = z.object({
  prompt: z.string().min(1),
  correct: z.string().min(1),
  wrong: z.tuple([z.string().min(1), z.string().min(1), z.string().min(1)]),
});

const schema_DefaultTrivia = z.object({
  id: z.string().regex(/^seed-[a-z0-9-]{3,27}$/),
  playCount: z.number().int().nonnegative(),
  title: z.string().min(1),
  description: z.string(),
  questions: z.array(schema_DefaultQuestion).min(7).max(25),
});

type DefaultQuestion = z.infer<typeof schema_DefaultQuestion>;
type DefaultTrivia = z.infer<typeof schema_DefaultTrivia>;

function q(prompt: string, correct: string, w1: string, w2: string, w3: string): DefaultQuestion {
  return { prompt, correct, wrong: [w1, w2, w3] };
}

/** Same shape as the body of `POST /api/trivias` (validated later by `schema_TriviaDraft`). */
function defaultTriviaDraftInput(trivia: DefaultTrivia): {
  readonly title: string;
  readonly description: string;
  readonly questions: ReadonlyArray<{
    readonly prompt: string;
    readonly choices: ReadonlyArray<string>;
    readonly correctChoiceIndex: number;
  }>;
} {
  return {
    title: trivia.title,
    description: trivia.description,
    questions: trivia.questions.map((question, i) => {
      const correctChoiceIndex = correctPosition(`${trivia.id}:${i}:${question.prompt}`);
      const choices = [...question.wrong];
      choices.splice(correctChoiceIndex, 0, question.correct);
      return { prompt: question.prompt, choices, correctChoiceIndex };
    }),
  };
}

